// --- ALGORITMO FISHER-YATES PARA BARAJADO PERFECTO ---
export function mezclarMazo(array) {
    const copia = [...array];
    for (let i = copia.length - 1; i > 0; i--) {
        const j = Math.floor(Math.random() * (i + 1));
        [copia[i], copia[j]] = [copia[j], copia[i]];
    }
    return copia;
}